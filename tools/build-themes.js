// Collects themes/*.json into themes/themes.js so the web page also works when opened as a local file.
// Usage: node tools/build-themes.js   (run after adding or editing a theme)
const fs = require("fs"), path = require("path");
const dir = path.join(__dirname, "..", "themes");
const list = fs.readdirSync(dir).filter(f => f.endsWith(".json")).sort().map(f => JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")));
const order = ["academic-blue-orange", "blue-orange-3d", "forest-ink", "crimson-gray", "deep-sea-tech"];
list.sort((a, b) => (order.indexOf(a.name) + 1 || 99) - (order.indexOf(b.name) + 1 || 99));
fs.writeFileSync(path.join(dir, "themes.js"), "/* Generated by tools/build-themes.js from themes/*.json — do not edit by hand. */\nwindow.DOC2PPT_THEMES = " + JSON.stringify(list, null, 1) + ";\n");
fs.writeFileSync(path.join(dir, "index.json"), JSON.stringify(list.map(t => ({ name: t.name, label: t.label, file: t.name + ".json" })), null, 2));
console.log("themes:", list.map(t => t.name).join(", "));
