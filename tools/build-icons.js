// Regenerates engine/icons.js from react-icons (Font Awesome 5 solid + Feather line icons).
// Usage: npm i react react-dom react-icons && node tools/build-icons.js
const React = require("react");
const RDS = require("react-dom/server");
const fa = require("react-icons/fa");
const fi = require("react-icons/fi");
const fs = require("fs");
const path = require("path");
const MAP = {
  robot: ["FaRobot", "FiCpu"], users: ["FaUsers", "FiUsers"], user: ["FaUserCheck", "FiUser"],
  chart: ["FaChartLine", "FiTrendingUp"], bar: ["FaChartBar", "FiBarChart2"], brain: ["FaBrain", "FiCpu"],
  coins: ["FaCoins", "FiDollarSign"], book: ["FaBookOpen", "FiBookOpen"], search: ["FaSearch", "FiSearch"],
  db: ["FaDatabase", "FiDatabase"], layers: ["FaLayerGroup", "FiLayers"], cogs: ["FaCogs", "FiSettings"],
  shield: ["FaShieldAlt", "FiShield"], bolt: ["FaBolt", "FiZap"], globe: ["FaGlobe", "FiGlobe"],
  sitemap: ["FaSitemap", "FiGitMerge"], check: ["FaCheckCircle", "FiCheckCircle"], warn: ["FaExclamationTriangle", "FiAlertTriangle"],
  up: ["FaArrowCircleUp", "FiArrowUpCircle"], down: ["FaArrowCircleDown", "FiArrowDownCircle"], target: ["FaBullseye", "FiTarget"],
  bulb: ["FaLightbulb", "FiStar"], flag: ["FaFlag", "FiFlag"], calendar: ["FaCalendarAlt", "FiCalendar"],
  file: ["FaFileAlt", "FiFileText"], link: ["FaLink", "FiLink"], scale: ["FaBalanceScale", "FiSliders"],
  camera: ["FaCamera", "FiCamera"], pin: ["FaMapMarkerAlt", "FiMapPin"], comments: ["FaComments", "FiMessageSquare"],
  tools: ["FaTools", "FiTool"], car: ["FaCar", "FiTruck"], building: ["FaBuilding", "FiHome"],
  industry: ["FaIndustry", "FiBox"], money: ["FaMoneyBillWave", "FiCreditCard"], clock: ["FaClock", "FiClock"],
  lock: ["FaLock", "FiLock"], key: ["FaKey", "FiKey"], cap: ["FaGraduationCap", "FiAward"],
  lab: ["FaFlask", "FiActivity"], project: ["FaProjectDiagram", "FiShare2"], list: ["FaListUl", "FiList"],
  star: ["FaStar", "FiStar"], hospital: ["FaHospital", "FiPlusSquare"], gamepad: ["FaGamepad", "FiPlay"],
  filter: ["FaFilter", "FiFilter"], eye: ["FaEye", "FiEye"], handshake: ["FaHandshake", "FiUserPlus"],
};
const out = {};
for (const [k, [s, l]] of Object.entries(MAP)) {
  if (!fa[s] || !fi[l]) throw new Error("missing icon " + k);
  const svg = (C) => RDS.renderToStaticMarkup(React.createElement(C, { color: "currentColor", size: "256" }))
    .replace(/ style="[^"]*"/, "").replace(/ height="256" width="256"/, ' width="256" height="256"');
  out[k] = { solid: svg(fa[s]), line: svg(fi[l]) };
}
const js = "/* Generated by tools/build-icons.js. Icons: Font Awesome Free 5 (CC BY 4.0) and Feather (MIT). */\n" +
  "(function (root) {\n  var ICONS = " + JSON.stringify(out) + ";\n" +
  "  if (typeof module === 'object' && module.exports) module.exports = ICONS; else root.DOC2PPT_ICONS = ICONS;\n" +
  "})(typeof self !== 'undefined' ? self : this);\n";
fs.writeFileSync(path.join(__dirname, "..", "engine", "icons.js"), js);
console.log("icons:", Object.keys(out).length);
